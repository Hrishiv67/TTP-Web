"""Writes lib/drawings.ts from the SVGs produced by gen_drawings.py.

    python scripts/emit_drawings_ts.py <dir-with-svgs> lib/drawings.ts
"""
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from compact import compact  # noqa: E402

src, out = Path(sys.argv[1]), Path(sys.argv[2])


def paths(svg_file):
    return [compact(d, 1) for d in re.findall(r' d="([^"]+)"', svg_file.read_text())]


# order matches the path order gen_drawings.py writes
TIRE_NAMES = ["rimFace", "rimRing", "rimDrop", "boltCircle", "handHoles", "hubRing", "lugNuts", "nutDots", "bore",
              "boreRing", "valve", "tread", "shoulder", "sidewallRib", "bead", "size", "sidewallText"]
tire = paths(src / "tire.svg")
assert len(tire) == len(TIRE_NAMES), len(tire)

truck_paths = paths(src / "truck.svg")
truck = dict(zip(["centre", "tractor", "cabDetail", "trailer", "kingpin"], truck_paths[:5]))
truck["axles"] = {
    g: dict(zip(["axle", "tyres", "treads"], truck_paths[5 + 3 * i: 8 + 3 * i]))
    for i, g in enumerate(["steer", "drive", "trailer"])
}

treads = {}
for k in ["steer", "drive", "trailer"]:
    main, sipes = paths(src / f"tread-{k}.svg")
    treads[k] = {"main": main, "sipes": sipes}


def ts(o, indent=2):
    if isinstance(o, dict):
        pad = " " * indent
        inner = ",\n".join(f"{pad}{k}: {ts(v, indent + 2)}" for k, v in o.items())
        return "{\n" + inner + "\n" + " " * (indent - 2) + "}"
    return json.dumps(o)


out.write_text(
    "/**\n"
    " * Path data for the site's technical drawings. Generated by\n"
    " * scripts/gen_drawings.py (geometry + Barlow Condensed lettering converted to\n"
    " * outlines) and compacted by scripts/compact.py — edit the generator, not this file.\n"
    " */\n\n"
    f"export const TIRE = {ts(dict(zip(TIRE_NAMES, tire)))} as const;\n\n"
    f"export const TRUCK = {ts(truck)} as const;\n\n"
    f"export const TREADS = {ts(treads)} as const;\n"
)
print("wrote", out)
